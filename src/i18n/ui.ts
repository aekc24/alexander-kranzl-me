/** Interface language: the site's language, e.g. 'de' or 'pt-BR' */
export const uiLang = siteConfig.lang ?? 'en';

const dictionary = dictionaries[uiLang] ?? dictionaries[uiLang.split('-')[0]] ?? {};

/** Interface string for `key` in the site's language, with `{name}` placeholders filled from `vars` */
export function t(key: UIKey, vars: Record<string, string | number> = {}): string {
  const text = dictionary[key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

/** Date in the site's language, e.g. "Oct 4, 2026" or "4. Okt. 2026" */
export function formatDate(date: Date, month: 'long' | 'short' = 'short'): string {
  return date.toLocaleDateString(uiLang, { year: 'numeric', month, day: 'numeric' });
}
